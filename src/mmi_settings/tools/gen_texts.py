"""i18n/<iso>.json -> <out>/com/mhi2/settings/Texts.java (the head unit has no
JSON parser). en.json is the reference and must hold every key the code uses;
another language may leave keys out (English is shown for those) but may not
add keys, change {placeholders}, or be anything but UTF-8. Any problem fails
the build, naming the file and the key.

    gen_texts.py <i18n dir> <output source dir>
"""
import json
import re
import sys
from pathlib import Path

LABEL_MAX = 40   # characters a row or its infoline shows (emulator: 73-char hint cut, 36-char row whole)


def fail(msg):
    sys.exit(f'gen_texts: {msg}')


def load(path):
    try:
        text = path.read_bytes().decode('utf-8')
    except UnicodeDecodeError as e:
        fail(f'{path.name}: not UTF-8 ({e})')
    try:
        data = json.loads(text)
    except ValueError as e:
        fail(f'{path.name}: not JSON ({e})')
    if not isinstance(data, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in data.items()):
        fail(f'{path.name}: must be one object of string keys and string texts')
    return data


def placeholders(s):
    return sorted(re.findall(r'\{[^}]*\}', s))


def java(s):
    return '"' + ''.join(c if 0x20 <= ord(c) < 0x7f and c not in '"\\' else f'\\u{ord(c):04x}' for c in s) + '"'


def main(src, out):
    files = sorted(Path(src).glob('*.json'))
    if not any(f.name == 'en.json' for f in files):
        fail('i18n/en.json missing')
    langs = {f.stem: load(f) for f in files}
    en = langs.pop('en')
    for iso, texts in langs.items():
        if not re.fullmatch(r'[a-z]{2}', iso):
            fail(f'{iso}.json: name must be an ISO 639-1 code (two lower-case letters)')
        for key, text in texts.items():
            if key not in en:
                fail(f'{iso}.json: key {key!r} is not in en.json')
            if placeholders(text) != placeholders(en[key]):
                fail(f'{iso}.json: key {key!r} has placeholders {placeholders(text)}, en.json {placeholders(en[key])}')
    order = ['en'] + sorted(langs)
    keys = list(en)
    for iso in order:
        texts = en if iso == 'en' else langs[iso]
        for key in keys:
            # rows and their hints (infoline) are one line; notes are multi-line popups, titles are separate
            if key in texts and not key.startswith(('note.', 'screen.')) and len(texts[key]) > LABEL_MAX:
                fail(f'{iso}.json: {key!r} is {len(texts[key])} characters; a row or its hint shows about {LABEL_MAX}')
    rows = []
    for iso in order:
        texts = en if iso == 'en' else langs[iso]
        rows.append('        {' + ', '.join(java(texts[k]) if k in texts else 'null' for k in keys) + '},')
    body = f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 top11r
// Generated by tools/gen_texts.py from i18n/*.json - do not edit.
package com.mhi2.settings;

public final class Texts {{
    static final String[] LANGUAGES = {{{', '.join(java(i) for i in order)}}};
    static final String[] KEYS = {{{', '.join(java(k) for k in keys)}}};
    static final String[][] TEXTS = {{
{chr(10).join(rows)}
    }};

    private Texts() {{
    }}

    /* The text of key in language iso (ISO 639-1), English if that language or text is missing; null for an unknown key. */
    public static String get(String key, String iso) {{
        int k = indexOf(KEYS, key);
        if (k < 0) {{
            return null;
        }}
        int l = iso == null ? -1 : indexOf(LANGUAGES, iso);
        String text = l > 0 ? TEXTS[l][k] : null;
        return text != null ? text : TEXTS[0][k];
    }}

    private static int indexOf(String[] a, String s) {{
        for (int i = 0; i < a.length; i++) {{
            if (a[i].equals(s)) {{
                return i;
            }}
        }}
        return -1;
    }}
}}
'''
    dest = Path(out) / 'com/mhi2/settings/Texts.java'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(body)
    print(f'gen_texts: {len(keys)} keys, languages: {", ".join(order)}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        fail('usage: gen_texts.py <i18n dir> <output source dir>')
    main(sys.argv[1], sys.argv[2])
